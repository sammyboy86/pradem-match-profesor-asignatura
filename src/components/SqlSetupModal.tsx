"use client";

import React, { useState } from "react";
import { Copy, Check, FileCode, X, Database, Terminal } from "lucide-react";

interface SqlSetupModalProps {
  isOpen: boolean;
  onClose: () => void;
  tableExists: boolean | null;
}

const SQL_MIGRATION_CODE = `-- Drop the existing function first to allow changing its return type
DROP FUNCTION IF EXISTS match_asignaturas_cosine(VECTOR, INT, FLOAT);

-- 1. Habilitar extensión pgvector
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Tabla de asignaturas con embedding de 768 dimensiones y soporte multi-vector
CREATE TABLE IF NOT EXISTS public.asignaturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave TEXT,
    nombre TEXT NOT NULL,
    cluster TEXT,
    fines_de_aprendizaje_o_formacion TEXT,
    contenido_tematico TEXT,
    actividades_de_aprendizaje TEXT,
    match_nombre BOOLEAN DEFAULT FALSE,
    match_semantico BOOLEAN DEFAULT FALSE,
    dot_product_match REAL,
    embedding_768 VECTOR(768),
    vectors JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Asegurar que las columnas cluster y vectors existan en tablas ya creadas
ALTER TABLE public.asignaturas ADD COLUMN IF NOT EXISTS cluster TEXT;
ALTER TABLE public.asignaturas ADD COLUMN IF NOT EXISTS vectors JSONB DEFAULT '{}'::jsonb;

-- 3. Índices HNSW, GIN y de búsqueda rápida
CREATE INDEX IF NOT EXISTS idx_asignaturas_embedding_768 
ON public.asignaturas 
USING hnsw (embedding_768 vector_cosine_ops);

CREATE INDEX IF NOT EXISTS idx_asignaturas_vectors_gin
ON public.asignaturas 
USING gin (vectors);

-- 3.1 Remover restricción única en clave para permitir materias con la misma clave (diferentes grupos/planes)
DROP INDEX IF EXISTS idx_asignaturas_clave;
ALTER TABLE public.asignaturas DROP CONSTRAINT IF EXISTS asignaturas_clave_key;
ALTER TABLE public.asignaturas DROP CONSTRAINT IF EXISTS idx_asignaturas_clave;
CREATE INDEX IF NOT EXISTS idx_asignaturas_clave ON public.asignaturas(clave);
CREATE INDEX IF NOT EXISTS idx_asignaturas_nombre ON public.asignaturas(nombre);
CREATE INDEX IF NOT EXISTS idx_asignaturas_cluster ON public.asignaturas(cluster);

-- 4. Habilitar RLS
ALTER TABLE public.asignaturas ENABLE ROW LEVEL SECURITY;

-- 5. Políticas de acceso
CREATE POLICY "Permitir lectura pública o anon" 
ON public.asignaturas FOR SELECT USING (true);

CREATE POLICY "Permitir inserción y actualización a usuarios autorizados/anon" 
ON public.asignaturas FOR ALL USING (true) WITH CHECK (true);

-- 5.1 Tabla de configuraciones de clusters compartidas en Supabase
CREATE TABLE IF NOT EXISTS public.cluster_configurations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    cluster_column TEXT NOT NULL DEFAULT 'cluster',
    cluster_betas JSONB NOT NULL DEFAULT '{}'::jsonb,
    default_betas JSONB NOT NULL DEFAULT '{}'::jsonb,
    custom_clusters JSONB NOT NULL DEFAULT '[]'::jsonb,
    author TEXT DEFAULT 'Usuario',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.cluster_configurations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir lectura publica cluster_configurations" ON public.cluster_configurations;
CREATE POLICY "Permitir lectura publica cluster_configurations" 
ON public.cluster_configurations FOR SELECT USING (true);

DROP POLICY IF EXISTS "Permitir insercion y edicion cluster_configurations" ON public.cluster_configurations;
CREATE POLICY "Permitir insercion y edicion cluster_configurations" 
ON public.cluster_configurations FOR ALL USING (true) WITH CHECK (true);

-- 6. Función RPC para búsqueda vectorial por similitud coseno
CREATE OR REPLACE FUNCTION match_asignaturas_cosine (
  query_embedding VECTOR(768),
  match_count INT DEFAULT 10,
  similarity_threshold FLOAT DEFAULT 0.0
)
RETURNS TABLE (
  id BIGINT,
  clave TEXT,
  nombre TEXT,
  contenido_tematico TEXT,
  match_nombre BOOLEAN,
  similarity FLOAT,
  cluster TEXT
)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  SELECT
    a.id,
    a.clave,
    a.nombre,
    a.contenido_tematico,
    a.match_nombre,
    (1 - (a.embedding_768 <=> query_embedding))::FLOAT AS similarity,
    a.cluster
  FROM public.asignaturas a
  WHERE a.embedding_768 IS NOT NULL
    AND (1 - (a.embedding_768 <=> query_embedding)) >= similarity_threshold
  ORDER BY a.embedding_768 <=> query_embedding ASC
  LIMIT match_count;
END;
$$;

-- 7. Función RPC para agregar columnas dinámicamente desde la app
CREATE OR REPLACE FUNCTION public.add_asignatura_column(col_name TEXT, col_type TEXT DEFAULT 'TEXT')
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  clean_col TEXT;
  clean_type TEXT;
BEGIN
  clean_col := lower(regexp_replace(col_name, '[^a-zA-Z0-9_]', '_', 'g'));
  clean_col := trim(both '_' from clean_col);
  IF clean_col IS NULL OR length(clean_col) = 0 THEN
    RETURN FALSE;
  END IF;

  clean_type := upper(trim(col_type));
  IF clean_type NOT IN ('TEXT', 'VARCHAR', 'INTEGER', 'BIGINT', 'REAL', 'DOUBLE PRECISION', 'BOOLEAN', 'TIMESTAMPTZ', 'JSONB') THEN
    clean_type := 'TEXT';
  END IF;

  EXECUTE format('ALTER TABLE public.asignaturas ADD COLUMN IF NOT EXISTS %I %s;', clean_col, clean_type);
  RETURN TRUE;
EXCEPTION
  WHEN OTHERS THEN
    RETURN FALSE;
END;
$$;

GRANT EXECUTE ON FUNCTION public.add_asignatura_column(TEXT, TEXT) TO anon, authenticated, service_role;`;

export default function SqlSetupModal({
  isOpen,
  onClose,
  tableExists,
}: SqlSetupModalProps) {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(SQL_MIGRATION_CODE);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 p-4 backdrop-blur-sm animate-in fade-in">
      <div className="relative flex max-h-[90vh] w-full max-w-3xl flex-col rounded-2xl border border-white/10 bg-slate-900 shadow-2xl">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-white/10 p-5">
          <div className="flex items-center gap-2.5">
            <div className="rounded-xl bg-amber-500/10 p-2 text-amber-400 border border-amber-500/20">
              <Database className="h-5 w-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-sm font-semibold text-white">Migración SQL para Supabase (pgvector)</h2>
                {tableExists === true && (
                  <span className="rounded-full bg-emerald-500/20 px-2 py-0.5 text-[10px] font-semibold text-emerald-300 border border-emerald-500/30">
                    Tabla detectada
                  </span>
                )}
                {tableExists === false && (
                  <span className="rounded-full bg-amber-500/20 px-2 py-0.5 text-[10px] font-semibold text-amber-300 border border-amber-500/30">
                    Pendiente de ejecutar
                  </span>
                )}
              </div>
              <p className="text-xs text-slate-400">
                Ejecuta este script en el SQL Editor de tu Dashboard de Supabase
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg p-1.5 text-slate-400 hover:bg-white/10 hover:text-white"
          >
            <X className="h-4 w-4" />
          </button>
        </div>

        {/* Info Banner */}
        <div className="border-b border-white/5 bg-slate-950/40 px-5 py-3 text-xs text-slate-300">
          <p>
            Crea o actualiza la tabla <code className="font-mono text-amber-300 font-semibold">asignaturas</code> con vector principal de 768d, soporte <code className="font-mono text-purple-300 font-semibold">multi-vector (JSONB)</code>, índice <code className="font-mono text-indigo-300">HNSW</code> y la función RPC <code className="font-mono text-indigo-300">match_asignaturas_cosine</code>.
          </p>
        </div>

        {/* Code Block */}
        <div className="relative flex-1 overflow-auto p-5">
          <pre className="rounded-xl border border-white/10 bg-slate-950 p-4 font-mono text-[11px] leading-relaxed text-indigo-200 selection:bg-indigo-600/40">
            <code>{SQL_MIGRATION_CODE}</code>
          </pre>
        </div>

        {/* Footer */}
        <div className="flex items-center justify-between border-t border-white/10 p-4 bg-slate-950/60">
          <div className="flex items-center gap-1.5 text-xs text-slate-400">
            <Terminal className="h-3.5 w-3.5 text-slate-500" />
            <span>Disponible también en <code className="font-mono text-slate-300">supabase/migrations/</code></span>
          </div>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={onClose}
              className="rounded-xl border border-white/10 bg-white/5 px-3.5 py-1.5 text-xs font-medium text-slate-300 hover:bg-white/10 hover:text-white"
            >
              Cerrar
            </button>

            <button
              type="button"
              onClick={handleCopy}
              className="flex items-center gap-1.5 rounded-xl bg-indigo-600 px-4 py-2 text-xs font-semibold text-white shadow-lg shadow-indigo-600/30 hover:bg-indigo-500 transition"
            >
              {copied ? (
                <>
                  <Check className="h-3.5 w-3.5 text-emerald-300" />
                  <span>¡Copiado al Portapapeles!</span>
                </>
              ) : (
                <>
                  <Copy className="h-3.5 w-3.5" />
                  <span>Copiar SQL</span>
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
