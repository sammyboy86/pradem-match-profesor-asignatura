import { NextRequest, NextResponse } from "next/server";
import { createDirectServerClient } from "@/lib/supabase/server";

export const maxDuration = 30;

const CLUSTER_CONFIG_TABLE_SQL = `-- Ejecuta este comando en el SQL Editor de Supabase si la tabla aún no existe:
CREATE TABLE IF NOT EXISTS public.cluster_configurations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    cluster_column TEXT NOT NULL DEFAULT 'cluster',
    cluster_betas JSONB NOT NULL DEFAULT '{}'::jsonb,
    default_betas JSONB NOT NULL DEFAULT '{}'::jsonb,
    custom_clusters JSONB NOT NULL DEFAULT '[]'::jsonb,
    author TEXT DEFAULT 'Usuario',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- RLS
ALTER TABLE public.cluster_configurations ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Permitir lectura publica cluster_configurations" 
ON public.cluster_configurations FOR SELECT USING (true);
CREATE POLICY "Permitir insercion y edicion cluster_configurations" 
ON public.cluster_configurations FOR ALL USING (true) WITH CHECK (true);`;

/**
 * GET /api/cluster-configurations: Obtiene todas las configuraciones de clusters guardadas en Supabase
 */
export async function GET() {
  try {
    const supabase = createDirectServerClient();

    const { data, error } = await supabase
      .from("cluster_configurations")
      .select("*")
      .order("updated_at", { ascending: false });

    if (error) {
      const isMissingTable =
        error.code === "42P01" ||
        error.message?.includes("does not exist") ||
        error.message?.includes("relation \"cluster_configurations\" does not exist");

      if (isMissingTable) {
        return NextResponse.json({
          success: false,
          tableExists: false,
          configurations: [],
          error: "La tabla 'cluster_configurations' aún no existe en Supabase.",
          sqlSetup: CLUSTER_CONFIG_TABLE_SQL,
        });
      }

      throw error;
    }

    const configurations = (data || []).map((row: any) => ({
      id: row.id,
      name: row.name,
      description: row.description || "",
      clusterColumn: row.cluster_column || "cluster",
      clusterBetas: row.cluster_betas || {},
      defaultBetas: row.default_betas || {},
      customClusters: Array.isArray(row.custom_clusters) ? row.custom_clusters : [],
      author: row.author || "Usuario",
      created_at: row.created_at,
      updated_at: row.updated_at,
    }));

    return NextResponse.json({
      success: true,
      tableExists: true,
      configurations,
    });
  } catch (error: any) {
    console.error("Error en GET /api/cluster-configurations:", error);
    return NextResponse.json(
      {
        success: false,
        error: error.message || "Error al obtener configuraciones de clusters",
        configurations: [],
      },
      { status: 500 }
    );
  }
}

/**
 * POST /api/cluster-configurations: Guarda o actualiza una configuración de clusters en Supabase
 */
export async function POST(req: NextRequest) {
  try {
    const supabase = createDirectServerClient();
    const body = await req.json().catch(() => ({}));

    const name = String(body.name || "").trim();
    if (!name) {
      return NextResponse.json(
        { success: false, error: "El nombre de la configuración es requerido." },
        { status: 400 }
      );
    }

    const payload: Record<string, any> = {
      name,
      description: body.description ? String(body.description).trim() : null,
      cluster_column: body.clusterColumn ? String(body.clusterColumn).trim() : "cluster",
      cluster_betas: body.clusterBetas && typeof body.clusterBetas === "object" ? body.clusterBetas : {},
      default_betas: body.defaultBetas && typeof body.defaultBetas === "object" ? body.defaultBetas : {},
      custom_clusters: Array.isArray(body.customClusters) ? body.customClusters : [],
      author: body.author ? String(body.author).trim() : "Usuario",
      updated_at: new Date().toISOString(),
    };

    const targetId =
      body.id != null && body.id !== ""
        ? typeof body.id === "number"
          ? body.id
          : !isNaN(Number(body.id))
          ? Number(body.id)
          : body.id
        : null;

    let result;
    const isUpdate = targetId != null;

    if (isUpdate) {
      // Actualizar existente
      result = await supabase
        .from("cluster_configurations")
        .update(payload)
        .eq("id", targetId)
        .select()
        .single();
    } else {
      // Insertar nuevo
      result = await supabase
        .from("cluster_configurations")
        .insert(payload)
        .select()
        .single();
    }

    if (result.error) {
      const isMissingTable =
        result.error.code === "42P01" ||
        result.error.message?.includes("does not exist") ||
        result.error.message?.includes("relation \"cluster_configurations\" does not exist");

      if (isMissingTable) {
        return NextResponse.json(
          {
            success: false,
            tableExists: false,
            error: "La tabla 'cluster_configurations' aún no existe en Supabase. Debes crearla en el SQL Editor.",
            sqlSetup: CLUSTER_CONFIG_TABLE_SQL,
          },
          { status: 400 }
        );
      }

      if (result.error.code === "PGRST116" || result.error.message?.includes("0 rows")) {
        return NextResponse.json(
          {
            success: false,
            error: `No se encontró la configuración con ID ${targetId} para actualizar en Supabase.`,
          },
          { status: 404 }
        );
      }

      throw result.error;
    }

    const row = result.data;
    const savedConfig = {
      id: row.id,
      name: row.name,
      description: row.description || "",
      clusterColumn: row.cluster_column || "cluster",
      clusterBetas: row.cluster_betas || {},
      defaultBetas: row.default_betas || {},
      customClusters: Array.isArray(row.custom_clusters) ? row.custom_clusters : [],
      author: row.author || "Usuario",
      created_at: row.created_at,
      updated_at: row.updated_at,
    };

    return NextResponse.json({
      success: true,
      configuration: savedConfig,
      message: isUpdate
        ? `Configuración '${savedConfig.name}' actualizada exitosamente en Supabase.`
        : `Configuración '${savedConfig.name}' guardada exitosamente en Supabase.`,
    });
  } catch (error: any) {
    console.error("Error en POST /api/cluster-configurations:", error);
    return NextResponse.json(
      { success: false, error: error.message || "Error al guardar configuración" },
      { status: 500 }
    );
  }
}

/**
 * DELETE /api/cluster-configurations?id=123: Elimina una configuración guardada
 */
export async function DELETE(req: NextRequest) {
  try {
    const supabase = createDirectServerClient();
    const { searchParams } = new URL(req.url);
    const id = searchParams.get("id");

    if (!id) {
      return NextResponse.json(
        { success: false, error: "Parámetro 'id' requerido." },
        { status: 400 }
      );
    }

    const { error } = await supabase
      .from("cluster_configurations")
      .delete()
      .eq("id", id);

    if (error) throw error;

    return NextResponse.json({
      success: true,
      message: `Configuración ${id} eliminada exitosamente.`,
    });
  } catch (error: any) {
    console.error("Error en DELETE /api/cluster-configurations:", error);
    return NextResponse.json(
      { success: false, error: error.message || "Error al eliminar configuración" },
      { status: 500 }
    );
  }
}
